-- Null means no limit.
create or replace function private.attempts_allowed(p_user_id uuid, p_test_id bigint)
returns int
language sql
stable
security definer
set search_path = ''
as $$
  select case
    when exists (
      select 1 from public.profiles p
      where p.id = p_user_id and p.role = 'admin'
    ) then null
    else 2 + coalesce((
      select g.extra_attempts
      from public.test_attempt_grants g
      where g.user_id = p_user_id and g.test_id = p_test_id
    ), 0)
  end;
$$;

create or replace function private.attempts_used(p_user_id uuid, p_test_id bigint)
returns int
language sql
stable
security definer
set search_path = ''
as $$
  select (
    select count(*) from public.results r
    where r.user_id = p_user_id and r.test_id = p_test_id
  )::int + (
    select count(*) from public.quiz_attempts a
    where a.user_id = p_user_id and a.test_id = p_test_id and a.finished_at is null
  )::int;
$$;

-- Keeps only answers that belong to the test. Ids are compared as text, so
-- malformed input is dropped instead of failing on a cast.
create or replace function private.clean_attempt_answers(p_test_id bigint, p_answers jsonb)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(jsonb_object_agg(q.id::text, a.id), '{}'::jsonb)
  from jsonb_each_text(p_answers) p
  join public.questions q on q.id::text = p.key and q.test_id = p_test_id
  join public.answers a on a.id::text = p.value and a.question_id = q.id;
$$;

