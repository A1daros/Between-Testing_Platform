create or replace function private.finalize_quiz_attempt(p_attempt public.quiz_attempts)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_answers   jsonb;
  v_score     numeric;
  v_total     numeric;
  v_result_id bigint;
begin
  v_answers := private.clean_attempt_answers(p_attempt.test_id, p_attempt.answers);

  select coalesce(sum(coalesce(tp.points, 1)), 0) into v_total
  from public.questions q
  left join public.test_parts tp on tp.id = q.part_id
  where q.test_id = p_attempt.test_id;

  if v_total = 0 then
    raise exception 'Test has no questions' using errcode = 'P0002';
  end if;

  select coalesce(sum(coalesce(tp.points, 1)), 0) into v_score
  from jsonb_each_text(v_answers) p
  join public.questions q on q.id::text = p.key
  join public.answers a on a.id::text = p.value and a.is_correct
  left join public.test_parts tp on tp.id = q.part_id;

  insert into public.results (test_id, user_id, score, total)
  values (p_attempt.test_id, p_attempt.user_id, v_score, v_total)
  returning id into v_result_id;

  insert into public.result_answers (result_id, question_id, answer_id)
  select v_result_id, p.key::bigint, p.value::bigint
  from jsonb_each_text(v_answers) p;

  update public.quiz_attempts a
  set answers = v_answers,
      finished_at = now(),
      result_id = v_result_id
  where a.id = p_attempt.id;

  return private.quiz_result_payload(v_result_id, p_attempt.user_id, p_attempt.test_id);
end;
$$;

-- Time is returned as seconds left, so a wrong clock on the device does not
-- matter. The minimum of 1 lets the client timer fire during the grace period.
create or replace function private.quiz_attempt_payload(p_attempt public.quiz_attempts)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select jsonb_build_object(
    'id', p_attempt.id,
    'answers', p_attempt.answers,
    'audio_plays', p_attempt.audio_plays,
    'question_index', p_attempt.question_index,
    'seconds_left', case when p_attempt.deadline_at is not null then
      greatest(ceil(extract(epoch from p_attempt.deadline_at - now()))::int, 1)
    end,
    'question_seconds_left', case when p_attempt.question_deadline_at is not null then
      greatest(ceil(extract(epoch from p_attempt.question_deadline_at - now()))::int, 1)
    end
  );
$$;

create or replace function private.resolve_active_attempt(p_user_id uuid, p_test_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_attempt public.quiz_attempts;
  v_payload jsonb;
  v_result  jsonb;
begin
  select * into v_attempt
  from public.quiz_attempts a
  where a.user_id = p_user_id and a.test_id = p_test_id and a.finished_at is null
  for update;

  if found then
    v_attempt := private.refresh_quiz_attempt(v_attempt);

    if private.is_attempt_expired(v_attempt) then
      v_result := private.finalize_quiz_attempt(v_attempt);
    else
      v_payload := private.quiz_attempt_payload(v_attempt);
    end if;
  end if;

  return jsonb_build_object(
    'attempt', v_payload,
    'expired_result', v_result,
    'attempts_used', private.attempts_used(p_user_id, p_test_id),
    'attempts_allowed', private.attempts_allowed(p_user_id, p_test_id)
  );
end;
$$;

