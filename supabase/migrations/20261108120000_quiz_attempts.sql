create or replace function public.start_quiz_attempt(p_test_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id        uuid := auth.uid();
  v_state          jsonb;
  v_allowed        int;
  v_timer_enabled  boolean;
  v_timer_type     text;
  v_timer_duration int;
  v_is_timed       boolean;
begin
  perform private.check_quiz_access(p_test_id);

  v_state := private.resolve_active_attempt(v_user_id, p_test_id);

  if v_state -> 'attempt' <> 'null'::jsonb
    or v_state -> 'expired_result' <> 'null'::jsonb then
    return v_state;
  end if;

  v_allowed := private.attempts_allowed(v_user_id, p_test_id);

  if v_allowed is not null
    and private.attempts_used(v_user_id, p_test_id) >= v_allowed then
    raise exception 'No attempts left' using errcode = '42501';
  end if;

  if not exists (select 1 from public.questions q where q.test_id = p_test_id) then
    raise exception 'Test has no questions' using errcode = 'P0002';
  end if;

  select t.timer_enabled, t.timer_type, t.timer_duration
  into v_timer_enabled, v_timer_type, v_timer_duration
  from public.tests t
  where t.id = p_test_id;

  v_is_timed := coalesce(v_timer_enabled, false) and coalesce(v_timer_duration, 0) > 0;

  insert into public.quiz_attempts (test_id, user_id, deadline_at, question_deadline_at)
  values (
    p_test_id,
    v_user_id,
    case when v_is_timed and v_timer_type = 'test'
      then now() + make_interval(secs => v_timer_duration) end,
    case when v_is_timed and v_timer_type = 'question'
      then now() + make_interval(secs => v_timer_duration) end
  )
  on conflict (user_id, test_id) where finished_at is null do nothing;

  return private.resolve_active_attempt(v_user_id, p_test_id);
end;
$$;

revoke all on function public.start_quiz_attempt(bigint) from public, anon;
grant execute on function public.start_quiz_attempt(bigint) to authenticated;

create or replace function public.save_quiz_progress(
  p_attempt_id bigint,
  p_answers jsonb,
  p_question_index int
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_attempt public.quiz_attempts;
begin
  if p_answers is null or jsonb_typeof(p_answers) <> 'object' then
    raise exception 'Invalid answers payload' using errcode = '22023';
  end if;

  v_attempt := private.lock_own_attempt(p_attempt_id);

  if v_attempt.finished_at is not null then
    return jsonb_build_object('status', 'finished');
  end if;

  v_attempt := private.refresh_quiz_attempt(v_attempt);
  v_attempt := private.apply_attempt_progress(v_attempt, p_answers, p_question_index);

  return jsonb_build_object(
    'status',
    case when private.is_attempt_expired(v_attempt) then 'expired' else 'active' end
  );
end;
$$;

revoke all on function public.save_quiz_progress(bigint, jsonb, int) from public, anon;
grant execute on function public.save_quiz_progress(bigint, jsonb, int) to authenticated;

-- Safe to repeat: a retry after a lost response returns the same result
-- instead of creating a second one.
create or replace function public.submit_quiz_attempt(p_attempt_id bigint, p_answers jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_attempt public.quiz_attempts;
begin
  if p_answers is null or jsonb_typeof(p_answers) <> 'object' then
    raise exception 'Invalid answers payload' using errcode = '22023';
  end if;

  v_attempt := private.lock_own_attempt(p_attempt_id);

  if v_attempt.finished_at is not null then
    return private.quiz_result_payload(
      v_attempt.result_id,
      v_attempt.user_id,
      v_attempt.test_id
    );
  end if;

  v_attempt := private.refresh_quiz_attempt(v_attempt);
  v_attempt := private.apply_attempt_progress(v_attempt, p_answers, null);

  return private.finalize_quiz_attempt(v_attempt);
end;
$$;

