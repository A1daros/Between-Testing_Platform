create or replace function public.grant_extra_attempt(p_user_id uuid, p_test_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.uid() is null then
    raise exception 'Not authenticated' using errcode = '28000';
  end if;

  if not private.is_admin() then
    raise exception 'Forbidden' using errcode = '42501';
  end if;

  if not exists (
    select 1 from public.profiles p
    where p.id = p_user_id and p.role = 'student'
  ) then
    raise exception 'Student not found' using errcode = 'P0002';
  end if;

  if not exists (select 1 from public.tests t where t.id = p_test_id) then
    raise exception 'Test not found' using errcode = 'P0002';
  end if;

  insert into public.test_attempt_grants (user_id, test_id, extra_attempts)
  values (p_user_id, p_test_id, 1)
  on conflict (user_id, test_id) do update
  set extra_attempts = public.test_attempt_grants.extra_attempts + 1,
      updated_at = now();

  return jsonb_build_object(
    'attempts_used', private.attempts_used(p_user_id, p_test_id),
    'attempts_allowed', private.attempts_allowed(p_user_id, p_test_id)
  );
end;
$$;

revoke all on function public.grant_extra_attempt(uuid, bigint) from public, anon;
grant execute on function public.grant_extra_attempt(uuid, bigint) to authenticated;

create or replace function public.get_correct_answers(p_test_id bigint)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_allowed int;
begin
  if auth.uid() is null then
    raise exception 'Not authenticated' using errcode = '28000';
  end if;

  if not private.is_admin() then
    v_allowed := private.attempts_allowed(auth.uid(), p_test_id);

    if not private.is_approved()
      or exists (
        select 1 from public.quiz_attempts a
        where a.user_id = auth.uid()
          and a.test_id = p_test_id
          and a.finished_at is null
      )
      or (
        select count(*) from public.results r
        where r.user_id = auth.uid() and r.test_id = p_test_id
      ) < v_allowed then
      raise exception 'Access denied' using errcode = '42501';
    end if;
  end if;

  return (
    select coalesce(
      jsonb_agg(
        jsonb_build_object('question_id', a.question_id, 'answer_id', a.id)
        order by a.question_id, a.id
      ),
      '[]'::jsonb
    )
    from public.answers a
    join public.questions q on q.id = a.question_id
    where q.test_id = p_test_id
      and a.is_correct
  );
end;
$$;

revoke all on function public.get_correct_answers(bigint) from public, anon;
grant execute on function public.get_correct_answers(bigint) to authenticated;

-- The baseline only adds the column grants on answers. On a new database the
-- default privileges also give table-wide select, so is_correct was readable
-- and the whole key could be fetched without any attempt.
revoke select on table public.answers from anon, authenticated;
grant select (id, question_id, answer_text) on table public.answers to anon, authenticated;

