-- Server-side quiz attempts. Before this, the timer, audio plays and answers
-- lived only in the browser, retakes were unlimited, and one empty submit_quiz
-- call unlocked the whole answer key.
--
-- Rules:
-- - two attempts per test; an admin can grant more per student and test;
-- - an attempt counts from the moment it starts, even if it ends up empty;
-- - results submitted before this migration count as used attempts;
-- - the key opens only when the attempts are used up and none is in progress;
-- - admins have no limit, so they can check their own tests.
--
-- Timed attempts accept answers until the deadline plus a short grace period
-- for the network. After that only the answers already saved are scored. An
-- abandoned timed attempt is scored the next time the student opens the test.
create table if not exists public.quiz_attempts (
  id bigint generated by default as identity primary key,
  test_id bigint not null references public.tests (id) on delete cascade,
  user_id uuid not null references auth.users (id) on delete cascade,
  started_at timestamptz not null default now(),
  deadline_at timestamptz,
  question_index int not null default 0,
  question_deadline_at timestamptz,
  answers jsonb not null default '{}'::jsonb,
  audio_plays jsonb not null default '{}'::jsonb,
  finished_at timestamptz,
  result_id bigint references public.results (id) on delete set null
);

create unique index if not exists quiz_attempts_one_active_idx
  on public.quiz_attempts (user_id, test_id)
  where finished_at is null;

create index if not exists quiz_attempts_test_id_idx
  on public.quiz_attempts (test_id);

alter table public.quiz_attempts enable row level security;

revoke all on table public.quiz_attempts from anon;
revoke insert, update, delete, truncate on table public.quiz_attempts from authenticated;

drop policy if exists "quiz_attempts: owner select" on public.quiz_attempts;
create policy "quiz_attempts: owner select"
  on public.quiz_attempts
  for select
  to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists "quiz_attempts: admin select" on public.quiz_attempts;
create policy "quiz_attempts: admin select"
  on public.quiz_attempts
  for select
  to authenticated
  using ((select private.is_admin()));

create table if not exists public.test_attempt_grants (
  user_id uuid not null references auth.users (id) on delete cascade,
  test_id bigint not null references public.tests (id) on delete cascade,
  extra_attempts int not null default 0 check (extra_attempts >= 0),
  updated_at timestamptz not null default now(),
  primary key (user_id, test_id)
);

create index if not exists test_attempt_grants_test_id_idx
