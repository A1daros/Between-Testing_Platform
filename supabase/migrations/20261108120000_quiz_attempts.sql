-- The signed audio URL itself can still be replayed: this limit covers the
-- player on the site, not a downloaded file.
create or replace function public.register_audio_play(p_attempt_id bigint, p_part_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  c_max_plays constant int := 2;
  v_attempt   public.quiz_attempts;
  v_plays     int;
begin
  v_attempt := private.lock_own_attempt(p_attempt_id);

  if v_attempt.finished_at is not null then
    raise exception 'Attempt is over' using errcode = '42501';
  end if;

  v_attempt := private.refresh_quiz_attempt(v_attempt);

  if private.is_attempt_expired(v_attempt) then
    raise exception 'Attempt is over' using errcode = '42501';
  end if;

  if not exists (
    select 1 from public.test_parts tp
    where tp.id = p_part_id
      and tp.test_id = v_attempt.test_id
      and tp.audio_path is not null
  ) then
    raise exception 'Audio not found' using errcode = 'P0002';
  end if;

  v_plays := coalesce((v_attempt.audio_plays ->> p_part_id::text)::int, 0);

  if v_plays >= c_max_plays then
    raise exception 'Audio plays exhausted' using errcode = '42501';
  end if;

  v_plays := v_plays + 1;

  update public.quiz_attempts a
  set audio_plays = a.audio_plays || jsonb_build_object(p_part_id::text, v_plays)
  where a.id = v_attempt.id;

  return jsonb_build_object('plays_used', v_plays);
end;
$$;

revoke all on function public.register_audio_play(bigint, bigint) from public, anon;
grant execute on function public.register_audio_play(bigint, bigint) to authenticated;

