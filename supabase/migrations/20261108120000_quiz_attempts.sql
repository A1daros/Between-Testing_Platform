create or replace function private.is_attempt_expired(p_attempt public.quiz_attempts)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(p_attempt.deadline_at + interval '15 seconds' < now(), false)
      or coalesce(p_attempt.question_deadline_at + interval '15 seconds' < now(), false);
$$;

-- With a per-question timer the clock keeps running while the page is closed,
-- so the position moves past every question whose time has run out.
create or replace function private.refresh_quiz_attempt(p_attempt public.quiz_attempts)
returns public.quiz_attempts
language plpgsql
security definer
set search_path = ''
as $$
declare
  c_grace    constant interval := interval '15 seconds';
  v_attempt  public.quiz_attempts := p_attempt;
  v_duration int;
  v_last     int;
begin
  if v_attempt.question_deadline_at is null then
    return v_attempt;
  end if;

  select t.timer_duration into v_duration
  from public.tests t
  where t.id = v_attempt.test_id;

  select count(*)::int - 1 into v_last
  from public.questions q
  where q.test_id = v_attempt.test_id;

  if coalesce(v_duration, 0) <= 0 then
    v_attempt.question_deadline_at := null;
  else
    while v_attempt.question_deadline_at + c_grace < now()
      and v_attempt.question_index < v_last
    loop
      v_attempt.question_index := v_attempt.question_index + 1;
      v_attempt.question_deadline_at :=
        v_attempt.question_deadline_at + c_grace + make_interval(secs => v_duration);
    end loop;
  end if;

  update public.quiz_attempts a
  set question_index = v_attempt.question_index,
      question_deadline_at = v_attempt.question_deadline_at
  where a.id = v_attempt.id;

  return v_attempt;
end;
$$;

-- With a per-question timer only the current question can be answered and the
-- position only moves forward, otherwise the timer could be bypassed.
create or replace function private.apply_attempt_progress(
  p_attempt public.quiz_attempts,
  p_answers jsonb,
  p_question_index int
)
returns public.quiz_attempts
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_attempt  public.quiz_attempts := p_attempt;
  v_clean    jsonb;
  v_last     int;
  v_current  text;
  v_duration int;
begin
  if private.is_attempt_expired(v_attempt) then
    return v_attempt;
  end if;

  v_clean := private.clean_attempt_answers(v_attempt.test_id, p_answers);

  select count(*)::int - 1 into v_last
  from public.questions q
  where q.test_id = v_attempt.test_id;

  if v_attempt.question_deadline_at is null then
    v_attempt.answers := v_clean;
    v_attempt.question_index := greatest(
      least(coalesce(p_question_index, v_attempt.question_index), v_last),
      0
    );
  else
    select q.id::text into v_current
    from public.questions q
    where q.test_id = v_attempt.test_id
    order by q.sort_order, q.id
    offset v_attempt.question_index
    limit 1;

    if v_current is not null and v_clean ? v_current then
      v_attempt.answers := v_attempt.answers
        || jsonb_build_object(v_current, v_clean -> v_current);
    end if;

    if p_question_index = v_attempt.question_index + 1
      and v_attempt.question_index < v_last then
      select t.timer_duration into v_duration
      from public.tests t
      where t.id = v_attempt.test_id;

      v_attempt.question_index := v_attempt.question_index + 1;
      v_attempt.question_deadline_at := now() + make_interval(secs => v_duration);
    end if;
  end if;

  update public.quiz_attempts a
  set answers = v_attempt.answers,
      question_index = v_attempt.question_index,
      question_deadline_at = v_attempt.question_deadline_at
  where a.id = v_attempt.id;

  return v_attempt;
end;
$$;

